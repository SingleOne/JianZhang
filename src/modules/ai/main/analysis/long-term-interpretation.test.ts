import { describe, expect, it } from 'vitest'
import type { CompactLongTermContext } from './long-term-context'
import {
  createModelCalculationReference,
  parseLongTermInterpretation
} from './long-term-interpretation'

function completeResult() {
  return {
    summary: '数据覆盖五个完整年度，以下内容仅说明历史指标与模型计算结果。',
    sections: [
      {
        id: 'operatingMetrics',
        observation: 'ROE 在五个报告年度间保持连续',
        evidence: [' 五年最低 ROE 18% ']
      },
      {
        id: 'financialStructure',
        observation: '报告期净负债为负值',
        evidence: ['净负债 -80 亿元']
      },
      {
        id: 'valuationMetrics',
        observation: '当前价格位于 250 日历史区间的 18% 位置',
        evidence: ['250 日位置 18%']
      }
    ],
    riskFacts: ['最近两个年度自由现金流数值方向不同'],
    uncertainties: ['缺少金融行业专用指标']
  }
}

describe('long-term AI interpretation validator', () => {
  it('keeps the fixed objective sections and trims evidence', () => {
    const result = parseLongTermInterpretation(
      JSON.stringify(completeResult()),
      '2026-10-13T15:00:00+08:00'
    )

    expect(result.schemaVersion).toBe(3)
    expect(result.sections).toHaveLength(3)
    expect(result.sections[0].evidence).toEqual(['五年最低 ROE 18%'])
    expect(result.sections[0].observation).toBe('ROE 在五个报告年度间保持连续')
    expect(result.generatedAt).toBe('2026-10-13T15:00:00+08:00')
  })

  it('accepts sections keyed by the required ids', () => {
    const payload = completeResult()
    const sections = Object.fromEntries(payload.sections.map(({ id, ...section }) => [id, section]))

    const result = parseLongTermInterpretation(
      JSON.stringify({ ...payload, sections }),
      '2026-10-13T15:00:00+08:00'
    )

    expect(result.sections.map((section) => section.id)).toEqual([
      'operatingMetrics',
      'financialStructure',
      'valuationMetrics'
    ])
  })

  it('converts internal names in a generated result into readable financial terms', () => {
    const payload = completeResult()
    payload.sections[0].evidence = [
      'fundamental.quality.metrics：netProfitCagr=6.0349%、deductedProfitRatio=95.2331%'
    ]
    payload.uncertainties = ['companyReportSummaries[0] 是2026年半年报的 AI 二次总结，未经审计。']

    const result = parseLongTermInterpretation(JSON.stringify(payload), '2026-10-28T10:00:00+08:00')

    expect(result.sections[0].evidence).toEqual([
      '财务质量指标：五年净利润复合年增长率：6.0349%、五年累计扣非归母净利润占归母净利润比例：95.2331%'
    ])
    expect(result.uncertainties).toEqual([
      '财报 AI 二次总结（第1项） 是2026年半年报的 AI 二次总结，未经审计。'
    ])
  })

  it('rejects output missing a fixed metric section', () => {
    const payload = completeResult()
    payload.sections.pop()
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('缺少经营、财务结构或估值指标')
  })

  it('rejects investment timing language', () => {
    const payload = completeResult()
    payload.summary = '当前买入时机有利。'
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('包含预测、评级或投资建议措辞')
  })

  it('rejects a DCF interval generated by the model', () => {
    const payload = completeResult()
    payload.sections[2].observation = 'DCF 数学区间约为 10 元至 15 元。'
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('不得自行输出 DCF 内容')
  })

  it('rejects an alternate DCF range generated by the model', () => {
    const payload = completeResult()
    payload.sections[2].observation = 'DCF 模型计算区间为 10—15 元。'
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('不得自行输出 DCF 内容')
  })

  it('rejects a DCF range separated by a field-internal line break', () => {
    const payload = completeResult()
    payload.sections[2].observation = 'DCF 区间\n10—15 元。'
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('不得自行输出 DCF 内容')
  })

  it('rejects DCF values outside the valuation section', () => {
    const payload = completeResult()
    payload.uncertainties = ['DCF 数学区间约为 10 元至 15 元。']
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('不得自行输出 DCF 内容')
  })

  it.each(['DCF 折现率为 8%', '折现率\n8%', '预测增长率 3%', '永续增长率为 2.5%'])(
    'rejects a model-generated DCF parameter: %s',
    (parameter) => {
      const payload = completeResult()
      payload.sections[2].evidence = [parameter]
      expect(() =>
        parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
      ).toThrow('不得自行输出 DCF 内容')
    }
  )

  it.each([
    'DCF 预测期为 5 年',
    '现金流折现法预测期为 5 年',
    '贴现现金流模型不可用',
    'WACC 为 8%',
    '终值增长率 3%',
    'terminalGrowthRate 为 3%'
  ])('rejects model-generated DCF content: %s', (content) => {
    const payload = completeResult()
    payload.sections[2].evidence = [content]
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('不得自行输出 DCF 内容')
  })

  it('rejects a single model value split across observation and evidence', () => {
    const payload = completeResult()
    payload.sections[2].observation = 'DCF 每股模型估值'
    payload.sections[2].evidence = ['19.02 元']
    expect(() =>
      parseLongTermInterpretation(JSON.stringify(payload), '2026-10-13T15:00:00+08:00')
    ).toThrow('包含单一模型估值')
  })

  it('builds the fixed DCF sentence from strict model inputs and appends it after validation', () => {
    const context = {
      valuation: {
        strictDcf: {
          analysis: {
            rangeLow: 10.126,
            rangeHigh: 15.684,
            scenarios: [
              { discountRate: 12, forecastGrowthRate: 1 },
              { discountRate: 10, forecastGrowthRate: 3 },
              { discountRate: 8, forecastGrowthRate: 5 }
            ]
          }
        }
      }
    } as unknown as CompactLongTermContext
    const reference = createModelCalculationReference(context)
    const result = parseLongTermInterpretation(
      JSON.stringify(completeResult()),
      '2026-10-13T15:00:00+08:00',
      reference
    )

    expect(result.modelCalculationReference).toBe(
      '在假设折现率8%至12%、未来增长率1%至5%的特定数理模型（如DCF）设定下，根据历史财务数据自动化计算所得的数学区间约为10.13元至15.68元。该结果仅为公式计算参考，当前市场价格受多重复杂因素影响，模型计算值不代表对该股票的未来实际定价或投资建议，请投资者注意价格波动与溢价风险。'
    )
  })
})
