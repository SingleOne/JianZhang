export interface IndicatorExplanation {
  definition: string
  formula: string
  interpretation: readonly string[]
  note: string
}

function maExplanation(period: number): IndicatorExplanation {
  return {
    definition: `最近 ${period} 个交易日收盘价的简单平均值，用来观察该时间尺度上的平均持仓成本和趋势基准。`,
    formula: `最近 ${period} 个已完成交易日的收盘价之和 ÷ ${period}。`,
    interpretation: [
      `最新收盘价位于 MA${period} 上方，表示价格高于这段时间的平均水平；位于下方则表示相对偏弱。`,
      '均线本身持续向上或向下，比单日站上、跌破更能说明趋势是否稳定。',
      '短期均线上穿长期均线通常代表趋势改善，反向交叉通常代表趋势转弱。'
    ],
    note: '均线是滞后指标，也可能形成动态支撑或压力，但一次触碰或突破不能单独作为买卖依据。'
  }
}

function emaExplanation(period: number): IndicatorExplanation {
  return {
    definition: `${period} 日指数移动平均线。它赋予近期收盘价更高权重，因此通常比同周期简单均线更快响应价格变化。`,
    formula: `今日 EMA = 昨日 EMA + 2 ÷ (${period} + 1) ×（今日收盘价 − 昨日 EMA）。`,
    interpretation: [
      `最新收盘价位于 EMA${period} 上方，表示当前价格高于近期加权平均水平；位于下方则相对偏弱。`,
      'EMA斜率向上代表加权成本正在抬升，斜率向下代表加权成本正在下降。',
      'EMA12变化较快，EMA26更加平滑；两者的距离和交叉是 MACD 的基础。'
    ],
    note: 'EMA对近期价格更敏感，也更容易在震荡行情中反复产生交叉信号，需要结合中长期趋势判断。'
  }
}

function intradayReturnExplanation(minutes: number): IndicatorExplanation {
  return {
    definition: `${minutes} 分钟收益表示当前行情价相对于约 ${minutes} 分钟前已完成分时柱收盘价的涨跌幅。`,
    formula: `（当前行情价 ÷ ${minutes} 根已完成 1 分钟柱之前的收盘价 − 1）× 100%。`,
    interpretation: [
      '数值大于0表示这段短窗内价格上涨，小于0表示价格下跌，接近0表示短窗方向不明显。',
      `它适合观察最近 ${minutes} 分钟的价格速度，并与1、3、5、15分钟窗口相互确认。`,
      '多个短窗同向通常说明盘中动量较一致，短窗与长窗方向相反可能意味着加速、减速或短暂反抽。'
    ],
    note: '当前端点使用最新行情价，起点使用已完成分时柱；开盘不久数据不足时显示为空，单个短窗不能代表全天趋势。'
  }
}

function openingRangeExplanation(minutes: 15 | 30, side: 'high' | 'low'): IndicatorExplanation {
  const isHigh = side === 'high'
  const label = isHigh ? '最高价' : '最低价'
  return {
    definition: `开盘后前 ${minutes} 分钟内所有已完成分时柱的${label}，用于标记早盘初始交易区间的${isHigh ? '上沿' : '下沿'}。`,
    formula: `取 9:30 至 ${minutes === 15 ? '9:44' : '9:59'} 之间已完成 1 分钟柱的${isHigh ? '最高价最大值' : '最低价最小值'}。`,
    interpretation: [
      `当前价格位于该${isHigh ? '高点之上' : '低点之下'}，表示价格已经${isHigh ? '突破' : '跌破'}早盘前${minutes}分钟区间。`,
      `价格反复回到该位置附近，说明开盘区间${isHigh ? '上沿' : '下沿'}正在被市场重新测试。`,
      `结合成交量放大和收盘能否站稳，可以区分有效${isHigh ? '突破' : '跌破'}与短暂越界。`
    ],
    note: `该价格只来自开盘前${minutes}分钟，不会随全天新高或新低变化；早盘数据未闭合时可能暂时为空。`
  }
}

